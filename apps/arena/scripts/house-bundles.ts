/**
 * Bundles each house bot into the single ESM file the sandbox loads (`export default <bot>`) and
 * writes them to `src/house-bundles.gen.ts` as strings. Runs before typecheck, `wrangler dev`
 * and `wrangler deploy` (the `build` command in wrangler.jsonc); the output is git-ignored.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { RANKED } from "@zerosnake/house-bots";
import { build } from "esbuild";

const appDir = join(import.meta.dirname, "..");
export const OUTPUT = join(appDir, "src/house-bundles.gen.ts");

/** The house bots the room fills with. */
export const HOUSE_KINDS = [...RANKED, "chaos"] as const;

export async function bundleHouseBots(): Promise<Record<string, string>> {
  const bundles: Record<string, string> = {};
  for (const kind of HOUSE_KINDS) {
    const out = await build({
      stdin: {
        contents: `export { ${kind} as default } from "@zerosnake/house-bots";`,
        resolveDir: appDir,
        loader: "ts",
        sourcefile: `${kind}.ts`,
      },
      bundle: true,
      format: "esm",
      platform: "neutral",
      target: "es2023",
      write: false,
    });
    bundles[kind] = out.outputFiles[0]?.text ?? "";
  }
  return bundles;
}

export function houseBundlesModule(bundles: Record<string, string>): string {
  return [
    "// Generated by scripts/house-bundles.ts. Do not edit.",
    `export const HOUSE_BUNDLES: Readonly<Record<string, string>> = ${JSON.stringify(bundles, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === import.meta.filename) {
  writeFileSync(OUTPUT, houseBundlesModule(await bundleHouseBots()));
}
